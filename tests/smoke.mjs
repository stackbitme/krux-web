import fs from "node:fs";
import { startSim } from "./node_sim.mjs";
const out = process.argv[2]; fs.mkdirSync(out, { recursive: true });
const t0 = Date.now();
const sim = await startSim({ outDir: out });
await sim.settle(1500, 120000);
console.log("first settle", Date.now() - t0, "ms, lcd", sim.lcd());
console.log(sim.shot("01-boot"));
await sim.tap(160, 400); await sim.settle();
console.log(sim.shot("02-after-tap"));
await sim.tap(160, 100); await sim.settle();
console.log(sim.shot("03-tap-top"));
console.log("files", Object.keys(sim.files));
sim.stop();
process.exit(0);

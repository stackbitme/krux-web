import fs from "node:fs";
import { startSim } from "./node_sim.mjs";
const out = process.argv[2]; fs.mkdirSync(out, { recursive: true });
const sim = await startSim({ outDir: out, log: false });
const step = async (name, fn) => { const t = Date.now(); await fn(); const r = await sim.ready(); sim.shot(name); console.log(name.padEnd(14), "ms", Date.now() - t, r); };
await sim.ready();
await step("b01", () => sim.tap(160, 100));
await step("b02", () => sim.tap(160, 100));
await step("b03", () => sim.tap(160, 60));
await step("b04", () => sim.tap(160, 60));
await step("b05-qr", async () => { await sim.sleep(300); sim.qr("before rebuild exercise history pipe know grape engine exit symbol west immune"); });
await step("b06-go", () => sim.tap(241, 447));
await step("b07-load", () => sim.tap(160, 175));
fs.writeFileSync(out + "/log.txt", sim.stdout.join("\n"));
sim.stop(); process.exit(0);
